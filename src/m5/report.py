"""Turn results/ into README tables and figures. README numbers come only from here."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

RESULTS_START = "<!-- results:start -->"
RESULTS_END = "<!-- results:end -->"
MODEL_LABELS = {
    "seasonal_naive": "Seasonal naive",
    "ma28": "Moving average (28 days)",
    "lgb": "LightGBM (4 weekly models)",
    "cb": "CatBoost (4 weekly models)",
    "lstm": "LSTM",
    "ensemble": "Ensemble",
}
LEVEL_LABELS = {
    "total": "Total",
    "state": "State",
    "store": "Store",
    "category": "Category",
    "department": "Department",
    "item_store": "Item × store",
}


def _md_table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|---|" + "---:|" * (len(header) - 1)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def _models(scores: pd.DataFrame) -> list[str]:
    present = set(scores["model"])
    return [m for m in MODEL_LABELS if m in present]


def _value(s: pd.DataFrame, **match) -> float:
    for key, val in match.items():
        s = s[s[key] == val]
    if len(s) != 1:
        raise ValueError(f"expected one score for {match}, found {len(s)}")
    return float(s["value"].iloc[0])


def level_table(scores: pd.DataFrame, split: str) -> str:
    s = scores[scores["split"] == split]
    header = ["Model", "WRMSSE", *[f"WAPE {label}" for label in LEVEL_LABELS.values()]]
    rows = []
    for model in _models(s):
        sm = s[s["model"] == model]
        row = [MODEL_LABELS[model], f"{_value(sm, metric='wrmsse'):.3f}"]
        row += [
            f"{_value(sm, metric='wape', level=level, week=0) * 100:.1f}%" for level in LEVEL_LABELS
        ]
        rows.append(row)
    return _md_table(header, rows)


def week_table(scores: pd.DataFrame, split: str, level: str = "store") -> str:
    s = scores[(scores["split"] == split) & (scores["metric"] == "wape") & (scores["level"] == level)]
    rows = [
        [MODEL_LABELS[m], *[f"{_value(s[s['model'] == m], week=k) * 100:.1f}%" for k in range(1, 5)]]
        for m in _models(s)
    ]
    return _md_table(["Model", "Week 1", "Week 2", "Week 3", "Week 4"], rows)


def render_results(results_dir: Path) -> str:
    results_dir = Path(results_dir)
    scores = pd.read_csv(results_dir / "scores.csv")
    weights = json.loads((results_dir / "ensemble_weights.json").read_text(encoding="utf-8"))
    meta = json.loads((results_dir / "metadata.json").read_text(encoding="utf-8"))
    commit = str(meta.get("evaluate", {}).get("commit", "unknown"))
    used = [f"{MODEL_LABELS[m]} {w:.1f}" for m, w in weights.items() if w > 0]
    parts = [
        "### Holdout (d_1914 to d_1941, scored once)",
        "",
        level_table(scores, "holdout"),
        "",
        "### Validation (d_1886 to d_1913)",
        "",
        level_table(scores, "validation"),
        "",
        "### Store-level WAPE by forecast week (holdout)",
        "",
        week_table(scores, "holdout"),
        "",
        f"Ensemble weights, chosen on validation WRMSSE: {', '.join(used) or 'no ensemble'}.",
        "",
        f"*Generated by `m5 report` from `results/` (code commit `{commit[:7]}`). "
        "Do not edit by hand.*",
    ]
    return "\n".join(parts)


def update_readme(readme: Path, block: str) -> None:
    readme = Path(readme)
    text = readme.read_text(encoding="utf-8")
    start, end = text.find(RESULTS_START), text.find(RESULTS_END)
    if start == -1 or end == -1 or end < start:
        raise ValueError(f"{readme} is missing the results markers")
    new = text[: start + len(RESULTS_START)] + "\n" + block + "\n" + text[end:]
    readme.write_text(new, encoding="utf-8")


def make_figures(results_dir: Path, figures_dir: Path) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    results_dir, figures_dir = Path(results_dir), Path(figures_dir)
    figures_dir.mkdir(parents=True, exist_ok=True)
    scores = pd.read_csv(results_dir / "scores.csv")
    hold = scores[scores["split"] == "holdout"]
    models = _models(hold)
    paths = []

    fig, ax = plt.subplots(figsize=(10, 4.5))
    levels = list(LEVEL_LABELS)
    width = 0.8 / len(models)
    for i, model in enumerate(models):
        values = [
            _value(hold[hold["model"] == model], metric="wape", level=lv, week=0) * 100
            for lv in levels
        ]
        ax.bar([x + i * width for x in range(len(levels))], values, width, label=MODEL_LABELS[model])
    ax.set_xticks([x + width * (len(models) - 1) / 2 for x in range(len(levels))])
    ax.set_xticklabels(LEVEL_LABELS.values())
    ax.set_ylabel("WAPE (%)")
    ax.set_title("Holdout WAPE by hierarchy level (lower is better)")
    ax.legend(fontsize=8)
    paths.append(figures_dir / "wape_by_level.png")
    fig.tight_layout()
    fig.savefig(paths[-1], dpi=150)
    plt.close(fig)

    total = pd.read_csv(results_dir / "total_holdout.csv")
    fig, ax = plt.subplots(figsize=(10, 4))
    ax.plot(total["d"], total["actual"], color="black", linewidth=2, label="Actual")
    for model in [m for m in ("ensemble", "lgb", "seasonal_naive") if m in total.columns]:
        ax.plot(total["d"], total[model], label=MODEL_LABELS[model])
    ax.set_xlabel("Day (d_1914 to d_1941)")
    ax.set_ylabel("Units sold, all series")
    ax.set_title("Total daily sales in the holdout period")
    ax.legend(fontsize=8)
    paths.append(figures_dir / "total_holdout.png")
    fig.tight_layout()
    fig.savefig(paths[-1], dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 4))
    store = hold[(hold["metric"] == "wape") & (hold["level"] == "store")]
    for model in models:
        sm = store[store["model"] == model]
        ax.plot([1, 2, 3, 4], [_value(sm, week=k) * 100 for k in range(1, 5)], marker="o",
                label=MODEL_LABELS[model])
    ax.set_xticks([1, 2, 3, 4])
    ax.set_xlabel("Forecast week")
    ax.set_ylabel("Store-level WAPE (%)")
    ax.set_title("Error by forecast week (holdout)")
    ax.legend(fontsize=8)
    paths.append(figures_dir / "wape_by_week.png")
    fig.tight_layout()
    fig.savefig(paths[-1], dpi=150)
    plt.close(fig)
    return paths
